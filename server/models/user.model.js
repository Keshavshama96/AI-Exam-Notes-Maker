//schema for the user 
import mongoose from "mongoose"

const userschema=new mongoose.Schema({
 // Stores user name.
  name:{
    type:String,
    required:true //User cannot be created without name. 
  },
  email:{//Stores user email.
    type:String,
    unique :true,//Every email must be unique.
     required:true ///email to dalna hi hoga
  },
  credits:{//Stores available AI credits.
    type:Number,
    default:50,//50 credits given to new user.(default)
    min:0//Credits cannot go below 0.
  },
  iscreditavailable:{//Indicates whether user can still use AI features.(mtlb credits hai ki nhi )
    type:Boolean,
    default:true
  },
  notes:{//Stores references of notes generated by the user.
  type:[mongoose.Schema.Types.ObjectId],
  ref:"Notes",
  default:[]
  }

},{timestamps:true})


const userModel=mongoose.model("userModel",userschema)

export default userModel